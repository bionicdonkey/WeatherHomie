"""Regenerate src/stormtracker/sources/bom_radar/sites_table.py from BOM's radar information pages.

Run by hand when BOM adds a radar:  python scripts/gen_radar_sites.py
Each page lists a site's name, its position (lat/long, usually 2 decimals) and a link to its IDRnnR loop page.
"""
import html
import re
import sys
import time
from pathlib import Path

import httpx

STATES = {"nsw": "NSW", "vic": "VIC", "qld": "QLD", "sa": "SA", "wa": "WA", "tas": "TAS", "nt": "NT"}
OUT = Path(__file__).resolve().parents[1] / "src/stormtracker/sources/bom_radar/sites_table.py"
SITE = re.compile(r'<div class="site-info">(.*?)(?=<div class="site-info">|<div class="page-menu|</div>\s*<!-- End: Content)', re.S)

rows: dict[str, tuple[str, str, float, float]] = {}
with httpx.Client(headers={"User-Agent": "StormTracker-dev (personal, build-time)"}, timeout=30, follow_redirects=True) as c:
    for s, label in STATES.items():
        text = c.get(f"https://reg.bom.gov.au/australia/radar/info/{s}_info.shtml").raise_for_status().text
        for m in SITE.finditer(text):
            blk = m.group(1)
            name = re.search(r"<h2>.*?</a>(.*?)</h2>", blk, re.S)
            loc = re.search(r"lat(?:itude)?\s*(-?[\d.]+)(?:&deg;)?\s*(South|North|S|N)?[\s,]*long(?:itude)?\s*(-?[\d.]+)(?:&deg;)?\s*(East|West|E|W)?", blk, re.I)
            ids = re.search(r"IDR(\d{2,3})[1-4]\.loop", blk)
            if not (name and loc and ids):
                print("skipped a block in", s, re.sub(r"\s+", " ", re.sub("<[^>]+>", "", blk))[:160], file=sys.stderr); continue
            lat = -abs(float(loc.group(1))) if (loc.group(2) or "")[:1].upper() == "S" or float(loc.group(1)) < 0 else float(loc.group(1))   # Australia: southern unless marked otherwise
            lon = -abs(float(loc.group(3))) if (loc.group(4) or "")[:1].upper() == "W" else abs(float(loc.group(3)))
            rows[f"IDR{ids.group(1)}"] = (html.unescape(re.sub(r"<[^>]+>", "", name.group(1))).strip(), label, lat, lon)
        time.sleep(1)

lines = ['"""BOM weather radar sites: id -> (name, state, lat, lon). Generated by scripts/gen_radar_sites.py; do not edit.',
         '', 'Positions are as published on BOM\'s radar information pages (mostly 2 decimals, about 1 km). Exact positions, where known,',
         'live in georef.RADAR_SITES and take precedence.', '"""', '', 'SITES: dict[str, tuple[str, str, float, float]] = {']
for k in sorted(rows):
    n, st, la, lo = rows[k]
    lines.append(f"    {k!r}: ({n!r}, {st!r}, {la}, {lo}),")
lines.append("}")
OUT.write_text("\n".join(lines) + "\n")
print(len(rows), "sites ->", OUT)
